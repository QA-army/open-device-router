import type { Allowance, Provider } from "../core/types.js";

// Renders docs/free-tiers.md from the registry so the page can never drift from the entries.

function host(url: string): string {
  return new URL(url).hostname.replace(/^www\./, "");
}

function amount(a: Allowance): string {
  if (a.unit === "unlimited") return "Unlimited";
  if (a.unit === "usd") return `$${a.amount} of usage`;
  const unit = a.unit.replace(/_/g, " ");
  const base = `${a.amount?.toLocaleString("en-US")} ${unit}${a.amount === 1 ? "" : "s"}`;
  const rates = Object.entries(a.per_minute ?? {}).map(([surface, rate]) => `${rate}/min on ${surface}`);
  return rates.length ? `${base} (${rates.join(", ")})` : base;
}

const RENEWAL: Record<Allowance["type"], string> = {
  self_hosted: "Your hardware",
  public_repo: "Ongoing, public repos",
  daily: "Daily",
  monthly: "Monthly",
  oss_program: "Open-source program, by application",
  one_time: "One time",
  unverified: "Not stated by vendor",
};

function yn(v: boolean | "unknown" | undefined): string {
  return v === true ? "Yes" : v === false ? "No" : "Unknown";
}

export function freeTiersMarkdown(providers: Provider[]): string {
  const order = ["baseline", "launch", "researched", "candidate"];
  const sorted = [...providers].sort(
    (a, b) => order.indexOf(a.status) - order.indexOf(b.status) || a.id.localeCompare(b.id),
  );
  const out: string[] = [];
  out.push("# Free tiers");
  out.push("");
  out.push("<!-- Generated by `npm run docs:free-tiers` from registry/providers/*.yaml. Do not edit by hand. -->");
  out.push("");
  out.push(
    "Every row is vendor-documented: it is what the vendor's own page said on the date in the last column. " +
      "Nothing here has been measured by this project yet. Vendors change free tiers without notice, so check the linked page before relying on a number.",
  );
  out.push("");
  out.push("| Provider | Status | Free allowance | Renews | Limits | Card | Phone | Source | Checked |");
  out.push("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const p of sorted) {
    const allowances = p.allowances.length ? p.allowances : [undefined];
    for (const a of allowances) {
      const limits = a
        ? [
            (a.scope ?? "").replace(/\.$/, ""),
            a.max_session_minutes ? `${a.max_session_minutes}-minute sessions` : "",
            a.max_parallel ? `${a.max_parallel} at once` : "",
            a.expires_days ? `expires after ${a.expires_days} days` : "",
            a.manual_only ? "manual testing only" : "",
          ]
            .filter(Boolean)
            .join("; ")
        : "";
      out.push(
        `| [${p.name}](${p.homepage}) | ${p.status} | ${a ? amount(a) : "None listed"} | ${a ? RENEWAL[a.type] : ""} | ${limits.replace(/\|/g, "/")} | ${p.signup.required ? yn(p.signup.card_required) : "n/a"} | ${p.signup.required ? yn(p.signup.phone_required) : "n/a"} | ${a ? `[${host(a.source)}](${a.source})` : ""} | ${p.checked_at} |`,
      );
    }
  }
  out.push("");
  out.push("Status: `baseline` needs no account. `launch` is one of the first routed targets. `researched` has signup and free tier checked. `candidate` has only its pricing page checked.");
  out.push("");
  out.push("Found a number that changed? Open a pull request against the provider's file in `registry/providers/`. See [CONTRIBUTING.md](../CONTRIBUTING.md).");
  out.push("");
  return out.join("\n");
}
